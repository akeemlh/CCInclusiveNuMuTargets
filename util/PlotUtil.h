#ifndef UTIL_PLOTUTILS_H
#define UTIL_PLOTUTILS_H

//A few frequently used plotting functions, mostly wrappers of MnvPlotter methods with the plots standarised for my thesis
//Prevents you having to do this everytime you want to produce a new but mostly similar plot

#include "TCanvas.h"
#include "PlotUtils/MnvPlotter.h"

void PlotDataStack1D(PlotUtils::MnvH1D& dataHist, std::vector<PlotUtils::MnvH1D*> stackHists, double dataPOT, double MCPOT, std::string outpathNoExt, std::string title = "", std::string xlabel = "", std::string ylabel = "", std::string variable = "", bool WithRatio = false)
{ //Plotting sidebands
    TCanvas can("Temp");
    // Uncertainty summary
    PlotUtils::MnvPlotter plotter;
    plotter.ApplyStyle(PlotUtils::kDefaultStyle);
    //plotter.axis_maximum = 0.4;

    TObjArray* arr = new TObjArray();
    std::vector<PlotUtils::MnvH1D*> clonedHists; //To keep track of hist objects generated by Clone() for later deletion, preventing memory leak
    for (auto& hist : stackHists)
    {
        PlotUtils::MnvH1D* clonedHist = hist->Clone();
        clonedHists.push_back(clonedHist);
        arr->Add(clonedHist);
    }

    plotter.axis_title_size_y=0.03;
    plotter.axis_title_size_x=0.03;
    plotter.axis_title_offset_x=1.8;
    plotter.axis_title_offset_y=1.8;

    PlotUtils::MnvH1D* dataHistToDraw = dataHist.Clone();
    plotter.DrawDataStackedMC(&dataHist, arr, (dataPOT/MCPOT), "TR", "Data", 2, 1, 3001, "MINER#nuA Segment", "# of Events");
    plotter.AddHistoTitle(title.c_str(), 0.039);
    can.Update();
    can.Print((outpathNoExt+".pdf").c_str());
    can.Print((outpathNoExt+".png").c_str());
    for (auto& hist : clonedHists) delete hist;
}




#endif //UTIL_PLOTUTILS_H